const interpolate = (template: string, vars?: TranslationVars): string =>
  template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = vars?.[key];
    return value === null || value === undefined ? "" : String(value);
  });

export const resolveLocaleFromHeaders = (
  headers: IncomingHttpHeaders | Headers | Record<string, string | string[] | undefined>,
): EmailLocale => {
  const read = (name: string): string | null => {
    if (headers instanceof Headers) {
      const value = headers.get(name);
      return value && value.trim().length > 0 ? value.trim() : null;
    }

    const record = headers as Record<string, string | string[] | undefined>;
    const raw = record[name] ?? record[name.toLowerCase()];
    if (Array.isArray(raw)) {
      return raw.find((entry) => typeof entry === "string" && entry.trim().length > 0)?.trim() ?? null;
    }
    return typeof raw === "string" && raw.trim().length > 0 ? raw.trim() : null;
  };

  const explicit = normalizeEmailLocale(read("x-koma-locale"));
  if (explicit) {
    return explicit;
  }

  return detectLocaleFromAcceptLanguage(read("accept-language")) ?? DEFAULT_EMAIL_LOCALE;
};

export const tServer = (
  locale: EmailLocale,
  key: string,
  vars?: TranslationVars,
): string => {
  const template =
    AUTH_MESSAGES[locale]?.[key] ??
    AUTH_MESSAGES[DEFAULT_EMAIL_LOCALE]?.[key] ??
    key;
  return interpolate(template, vars);
};
