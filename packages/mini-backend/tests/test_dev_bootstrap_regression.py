SYSTEM = platform.system()


def _profile_mapping() -> dict[tuple[str, str], str]:
    spec = importlib.util.spec_from_file_location(
        "ensure_mini_deps_map", MINI_BACKEND_DIR / "scripts" / "ensure-mini-deps.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    mapping: dict[tuple[str, str], str] = module.PROFILE_REQUIREMENTS
    return mapping


def _recorded_uv_calls(record_path: Path) -> list[list[str]]:
    raw_lines = record_path.read_text(encoding="utf-8").splitlines()
    return [json.loads(line) for line in raw_lines]


def _uv_subcommand(argv: list[str]) -> str:
    return argv[argv.index("pip") + 1] if "pip" in argv else ""


def _legacy_effective_requirements() -> RequirementSet:
    base = RequirementSet()
    read_requirements(
        MINI_BACKEND_DIR / "requirements.txt", root=MINI_BACKEND_DIR, result=base
    )
    profile = RequirementSet()
    read_requirements(
        MINI_BACKEND_DIR / _profile_mapping()[("nvidia-cuda-legacy", SYSTEM)],
        root=MINI_BACKEND_DIR,
        result=profile,
    )
    return effective_requirements(
        base,
        profile,
        selected="nvidia-cuda-legacy",
        expected_onnx="onnxruntime-gpu",
    )


@pytest.mark.skipif(
    SYSTEM not in {"Windows", "Linux"},
    reason="the declared nvidia-cuda-legacy profile has no requirement file on this platform",
)
async def test_provisioning_the_declared_profile_replaces_the_clobbered_cpu_runtime(
    caplog: pytest.LogCaptureFixture,
    fake_child_scripts: tuple[Path, Path],
    fake_interpreter_argv: Callable[[str], list[str]],
    fresh_mini_venv: tuple[Path, Path],
    tmp_path: Path,
) -> None:
    caplog.set_level(logging.INFO)
    uv_script, _ = fake_child_scripts
    record = tmp_path / "uv-argv.record"
    snapshot = record.with_suffix(".requirement.lock")
    clobbered_installed = {"onnxruntime", "numpy"}
    environment_root, target_python = fresh_mini_venv

    code = await provision(
        MINI_BACKEND_DIR,
        _profile_mapping(),
        Settings(profile="nvidia-cuda-legacy"),
        environment_root=environment_root,
        target_python=target_python,
        installed_distributions=lambda: clobbered_installed,
        uv_argv=[
            sys.executable,
            str(uv_script),
            "--mode",
            "succeed",
            "--lock",
            LOCK_WITH_TORCH,
            "--record",
            str(record),
            "--snapshot-requirement",
            str(record.with_suffix(".requirement.lock")),
            "--",
        ],
        interpreter_argv=fake_interpreter_argv("succeed"),
    )

    assert code == EXIT_OK, f"the declared-profile provision must finish, got exit {code}"
    calls = _recorded_uv_calls(record)
    subcommands = [_uv_subcommand(call) for call in calls]
    assert subcommands == ["compile", "uninstall", "install", "check"], subcommands

    install_call = calls[subcommands.index("install")]
    if SYSTEM == "Windows":
        installed_lock = Path(snapshot).read_text(encoding="utf-8")
        assert "torch==2.15.0" not in installed_lock, (
            "the lock handed to the install must not carry torch on Windows "
            "CUDA profiles: PyPI's wheel is CPU-only and would clobber the "
            "CUDA build on every run"
        )
        assert "torchvision==0.29.2" not in installed_lock
        assert "easyocr==1.7.2" in installed_lock, (
            "the trim removes only the torch family"
        )

    uninstall_call = calls[subcommands.index("uninstall")]
    assert "onnxruntime" in uninstall_call, (
        "the clobbered CPU variant is what the declared profile removes first"
    )

    assert "--require-hashes" in install_call and "--no-deps" in install_call, install_call
    reinstalled = [
        install_call[position + 1]
        for position, token in enumerate(install_call)
        if token == "--reinstall-package"
    ]
    assert "onnxruntime-gpu" in reinstalled, reinstalled

    assert _event_payloads(caplog.records, "dependencies.failed") == []
    assert [
        payload.get("profile") for payload in _event_payloads(caplog.records, "dependencies.ready")
    ] == ["nvidia-cuda-legacy"]


@pytest.mark.skipif(
    SYSTEM != "Windows",
    reason=(
        "only the legacy Windows profile filters the base numpy>=2.0.0 pin: "
        "dependencies.py narrows NumPy for that platform, and requirements-base-no-ort.txt "
        "is the file the legacy profile includes"
    ),
)
def test_the_declared_profile_end_state_names_both_pins_it_installs() -> None:
    effective = _legacy_effective_requirements()
    lines = [str(item) for item in effective.requirements]

    assert "onnxruntime-gpu==1.18.1" in lines
    assert "onnxruntime==1.22.1" not in lines

    # torch lines flow through untouched: the authoritative handling is the
    # lock trim (drop_torch_entries_from_lock, asserted in the harness test
    # below) plus the CUDA wheel install (_ensure_torch_cuda).

    numpy_specs = [
        item for item in effective.requirements if canonicalize_name(item.name) == "numpy"
    ]
    assert numpy_specs, lines
    assert "numpy<2" in lines
    assert "numpy>=2.0.0" not in lines, (
        "the widened base pin is what resolved NumPy 2.5.4 over the 1.26.4 the GPU runtime needs"
    )
    assert not any(item.specifier.contains("2.5.4") for item in numpy_specs), lines


