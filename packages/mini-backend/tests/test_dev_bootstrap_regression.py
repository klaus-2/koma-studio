async def _provision(
    *,
    mini_venv: tuple[Path, Path],
    settings: Settings,
    uv_argv: list[str],
    interpreter_argv: list[str],
    installed_distributions: Callable[[], set[str]],
    red_reason: str,
    installed_version: Callable[[str], str | None] | None = None,
) -> int:
    environment_root, target_python = mini_venv
    try:
        return await provision(
            MINI_BACKEND_DIR,
            EMPTY_MAPPING,
            settings,
            environment_root=environment_root,
            target_python=target_python,
            installed_distributions=installed_distributions,
            installed_version=installed_version,
            uv_argv=uv_argv,
            interpreter_argv=interpreter_argv,
        )
    except DependencyError as exc:
        pytest.fail(
            f"provision() raised {type(exc).__name__}: {exc} instead of returning an "
            f"exit code — {red_reason}"
        )


def _emitted_text(records: list[logging.LogRecord]) -> str:
    formatter = JsonFormatter()
    return "\n".join(formatter.format(record) for record in records)


def _stage_event_count(records: list[logging.LogRecord], stage: str) -> int:
    formatter = JsonFormatter()
    matches = 0
    for record in records:
        payload = json.loads(formatter.format(record))
        if payload.get("event") == "dependencies.command" and payload.get("stage") == stage:
            matches += 1
    return matches


def _event_payloads(
    records: list[logging.LogRecord], event: str
) -> list[dict[str, object]]:
    formatter = JsonFormatter()
    payloads: list[dict[str, object]] = []
    for record in records:
        payload: dict[str, object] = json.loads(formatter.format(record))
        if payload.get("event") == event:
            payloads.append(payload)
    return payloads


def test_stderr_tail_travels_the_json_scalar_filter() -> None:
    tail = "FAKE_CHILD_FAIL_1 transient error: connection reset by peer"
    record = logging.LogRecord(
        name="mini_backend_tools.dependencies",
        level=logging.ERROR,
        pathname=__file__,
        lineno=0,
        msg="dependencies.failed",
        args=(),
        exc_info=None,
    )
    record.stage = "resolve"
    record.exit_code = 1
    record.stderr_tail = tail
    payload = json.loads(JsonFormatter().format(record))
    assert payload["stderr_tail"] == tail
    assert payload["stage"] == "resolve"
    assert payload["exit_code"] == 1


