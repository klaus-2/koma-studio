    code = await provision(
        MINI_BACKEND_DIR,
        _profile_mapping(),
        Settings(profile="nvidia-cuda-legacy"),
        environment_root=environment_root,
        target_python=target_python,
        installed_distributions=lambda: mixed_families,
        uv_argv=[
            sys.executable,
            str(uv_script),
            "--mode",
            "succeed",
            "--record",
            str(record),
            "--",
        ],
        interpreter_argv=fake_interpreter_argv("succeed"),
    )

    assert code == EXIT_OK, f"the declared-profile provision must finish, got exit {code}"
    calls = _recorded_uv_calls(record)
    uninstall_call = next(call for call in calls if _uv_subcommand(call) == "uninstall")
    assert "nvidia-cudnn-cu12" in uninstall_call, (
        "the cu12 (cuDNN 9) wheels are the off-family on the Windows legacy "
        "profile and must be removed before the CUDA provider loads"
    )
    assert "onnxruntime" in uninstall_call
    assert "nvidia-cublas-cu11" not in uninstall_call, (
        "the cu11 wheels are the profile's own family and must never be removed"
    )
