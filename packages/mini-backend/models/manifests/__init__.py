"""Generated manifest of every managed model's assets.

Each entry carries the asset's path, its real byte size and its sha256, so a
declared size can never drift away from the digest that protects it. The
manifest is generated by ``scripts/generate_model_asset_manifest.py`` and
checked in CI.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

MANIFEST_PATH = Path(__file__).resolve().parent / "model-assets.json"


@lru_cache(maxsize=1)
def load_manifest() -> dict[str, Any]:
    """The whole manifest: {"models": {model_id: {...}}}."""
    return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))


def model_entry(model_id: str) -> dict[str, Any] | None:
    """The manifest entry of one model, or None when it is not managed."""
    models = load_manifest().get("models")
    if not isinstance(models, dict):
        return None
    entry = models.get(model_id)
    return entry if isinstance(entry, dict) else None
