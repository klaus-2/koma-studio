"""Generate the assets/resources/index.ts barrel with explicit imports.

Explicit imports (instead of import.meta.glob) mean a missing or renamed
file breaks the typecheck instead of silently disappearing at runtime.

Usage: python -I gen_icons_index.py <assets-dir>
"""

import os
import re
import sys


def to_ident(slug):
    ident = re.sub(r"[^a-zA-Z0-9]+", " ", slug).title().replace(" ", "")
    if not ident:
        ident = "Icon"
    if ident[0].isdigit():
        ident = f"I{ident}"
    return ident


def main():
    assets_dir = sys.argv[1]
    names = sorted(
        f for f in os.listdir(assets_dir) if f.lower().endswith(".png")
    )

    lines = [
        "/**",
        " * Catalog artwork, one square icon per entry.",
        " *",
        " * The files are fetched once during curation, trimmed to a square and",
        " * resized to 96x96 so the cards stay sharp without a network round trip.",
        " * Generated by `packages/interface/scripts/generate-resource-icons-index.py`.",
        " */",
        "",
    ]

    for name in names:
        slug = name[: -len(".png")]
        lines.append(f"import {to_ident(slug)} from './{name}';")

    lines.append("")
    lines.append("export const RESOURCE_ICONS: Readonly<")
    lines.append("  Record<string, string>")
    lines.append("> = Object.freeze({")
    for name in names:
        slug = name[: -len(".png")]
        lines.append(f"  '{slug}': {to_ident(slug)},")
    lines.append("});")
    lines.append("")
    lines.append("/**")
    lines.append(" * Resolves the packaged artwork for a catalog entry.")
    lines.append(" *")
    lines.append(" * @param slug - The `image` slug carried by the entry, if any.")
    lines.append(" * @returns The packaged asset URL, or undefined when the entry has none.")
    lines.append(" */")
    lines.append("export const getResourceIcon = (")
    lines.append("  slug: string | undefined,")
    lines.append("): string | undefined =>")
    lines.append("  slug ? RESOURCE_ICONS[slug] : undefined;")
    lines.append("")

    out_path = os.path.join(assets_dir, "index.ts")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))

    print(f"WROTE {out_path} ({len(names)} icons, {len(lines)} lines)")


if __name__ == "__main__":
    main()
